# input() is designed to ask the user a question, or derive from it an answer

prompt = input("What's your favorite color?")
num = int(input("Name a random number"))
print(f"My favorite color is {prompt}, and I like the number {num}.")

# len() is used to count the amount of items in an object
text = "Hello World!"
print(len(text))

# Output: 12

shopping_list = ["apples", "milk", "bread", "eggs"]
print(len(shopping_list))

# Output: 4
